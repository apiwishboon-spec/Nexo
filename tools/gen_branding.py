#!/usr/bin/env python3
"""Generate derived branding assets from the source logos in app/assets/branding.

Inputs (drop-in, provided by the project owner):
  app/assets/branding/app-logo.png       app/launcher logo
  app/assets/branding/firmware-logo.png  Cardputer screen logo

Outputs (generated, do not edit by hand):
  app/assets/branding/app-icon-foreground.png   432x432 Android adaptive foreground
  firmware/src/ui/assets/firmware_logo.h        RGB565 array for the 240x135 screen
"""
from __future__ import annotations

import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND = os.path.join(ROOT, "app", "assets", "branding")
FW_ASSET = os.path.join(ROOT, "firmware", "src", "ui", "assets", "firmware_logo.h")

# Matches nexo::theme::kBackground = rgb(18, 19, 22)
BG = (18, 19, 22)

# Cardputer display is 240x135; keep a small margin.
FW_MAX_W = 220
FW_MAX_H = 110


def load_content(path: str) -> Image.Image:
    img = Image.open(path).convert("RGBA")
    bbox = img.getchannel("A").getbbox()
    return img.crop(bbox) if bbox else img


def gen_app_foreground() -> None:
    src = load_content(os.path.join(BRAND, "app-logo.png"))
    canvas = Image.new("RGBA", (432, 432), (0, 0, 0, 0))
    scale = min(280 / src.width, 280 / src.height)
    size = (max(1, round(src.width * scale)), max(1, round(src.height * scale)))
    src = src.resize(size, Image.LANCZOS)
    canvas.alpha_composite(src, ((432 - src.width) // 2, (432 - src.height) // 2))
    out = os.path.join(BRAND, "app-icon-foreground.png")
    canvas.save(out)
    print("wrote", os.path.relpath(out, ROOT), canvas.size)


def gen_firmware_logo() -> None:
    src = load_content(os.path.join(BRAND, "firmware-logo.png"))
    scale = min(FW_MAX_W / src.width, FW_MAX_H / src.height)
    w = max(1, round(src.width * scale))
    h = max(1, round(src.height * scale))
    src = src.resize((w, h), Image.LANCZOS)

    bg = Image.new("RGBA", (w, h), (*BG, 255))
    flat = Image.alpha_composite(bg, src).convert("RGB")

    values = []
    for (r, g, b) in flat.getdata():
        values.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))

    os.makedirs(os.path.dirname(FW_ASSET), exist_ok=True)
    with open(FW_ASSET, "w") as f:
        f.write("// Generated by tools/gen_branding.py - do not edit by hand.\n")
        f.write("// Standard RGB565; draw with setSwapBytes(true) + pushImage().\n")
        f.write("#pragma once\n\n#include <cstdint>\n\n")
        f.write("namespace nexo {\n")
        f.write(f"static const int kFirmwareLogoW = {flat.width};\n")
        f.write(f"static const int kFirmwareLogoH = {flat.height};\n")
        f.write("static const uint16_t kFirmwareLogo[] = {\n")
        for i in range(0, len(values), 12):
            row = ", ".join(f"0x{v:04X}" for v in values[i:i + 12])
            f.write("    " + row + ",\n")
        f.write("};\n\n}  // namespace nexo\n")
    print(f"wrote {os.path.relpath(FW_ASSET, ROOT)} ({flat.width}x{flat.height})")


def main() -> None:
    gen_app_foreground()
    gen_firmware_logo()


if __name__ == "__main__":
    main()
